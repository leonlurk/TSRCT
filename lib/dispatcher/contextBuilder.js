// Phase 2: build the project-context markdown bundle that gets prepended to
// every Claude Code prompt at dispatch time.
//
// Sources combined:
//   1. Vault page (vault/projects/<Project>.md)               — what the project is
//   2. git log --oneline -30 in the project repo path         — what changed lately
//   3. The 3 most recently dispatched tasks for this project   — what was just asked
//   4. Decisions Log relevant snippets (if it exists)         — why we made past choices
//
// All wrapped in a CONTEXT_PRELUDE block that Claude can see at the top of the prompt.

const fs = require('fs');
const path = require('path');
const paths = require('../paths');
const { execFileSync } = require('child_process');

const projects = require('./projectContext');
const restrictedGuard = require('./restrictedGuard');
const db = require('./db');

const MAX_VAULT_CHARS = 4000;
const MAX_GITLOG_CHARS = 1500;
const MAX_DECISIONS_CHARS = 2000;
const MAX_TOTAL_CHARS = 9000;

const VAULT_ROOT = paths.VAULT_ROOT;

function safeReadFile(filepath, maxChars) {
    try {
        if (!fs.existsSync(filepath)) return '';
        const data = fs.readFileSync(filepath, 'utf8');
        return data.length > maxChars ? data.slice(0, maxChars) + '\n[...truncated]' : data;
    } catch {
        return '';
    }
}

function clip(s, max) {
    if (!s) return '';
    return s.length > max ? s.slice(0, max) + '\n[...truncated]' : s;
}

function vaultPageFor(projectName) {
    const dir = path.join(VAULT_ROOT, 'projects');
    if (!fs.existsSync(dir)) return '';
    // Try exact match first, then case-insensitive.
    const exact = path.join(dir, `${projectName}.md`);
    if (fs.existsSync(exact)) return safeReadFile(exact, MAX_VAULT_CHARS);
    const lower = projectName.toLowerCase();
    const entries = fs.readdirSync(dir);
    const hit = entries.find(f => f.toLowerCase() === `${lower}.md`);
    return hit ? safeReadFile(path.join(dir, hit), MAX_VAULT_CHARS) : '';
}

function decisionsLogSnippet(projectName) {
    // Split per project on 2026-09-24: the project's own file, newest first.
    const dir = path.join(VAULT_ROOT, 'wiki', 'decisions');
    try {
        const hit = fs.readdirSync(dir).find(f => f.toLowerCase() === `${String(projectName).toLowerCase()}.md`);
        if (hit) return clip(safeReadFile(path.join(dir, hit), 60000), MAX_DECISIONS_CHARS);
    } catch { /* no split folder: the single log below */ }
    const file = path.join(VAULT_ROOT, 'wiki', 'Decisions Log.md');
    if (!fs.existsSync(file)) return '';
    const all = safeReadFile(file, 200000);
    if (!all) return '';
    // Pull paragraphs that mention this project (case-insensitive).
    const blocks = all.split(/\n(?=##\s|\n#\s)/);
    const matching = blocks.filter(b => b.toLowerCase().includes(projectName.toLowerCase()));
    if (!matching.length) return '';
    return clip(matching.slice(0, 3).join('\n\n'), MAX_DECISIONS_CHARS);
}

function gitLogFor(projectPath) {
    if (!projectPath || !fs.existsSync(projectPath)) return '';
    try {
        const out = execFileSync('git', ['-C', projectPath, 'log', '--oneline', '-30'], {
            encoding: 'utf8',
            timeout: 5000,
            stdio: ['ignore', 'pipe', 'ignore'],
        });
        return clip(out.trim(), MAX_GITLOG_CHARS);
    } catch {
        return '';
    }
}

function recentTaskSummary(projectName) {
    const tasks = db.getRecentTasksForProject(projectName, 3);
    if (!tasks.length) return '';
    return tasks.map(t => {
        const when = t.dispatched_at
            ? new Date(t.dispatched_at).toISOString().slice(0, 10)
            : 'pending';
        const prompt = (t.composed_prompt || t.raw_text || '').replace(/\s+/g, ' ').slice(0, 200);
        return `- [${when}] ${t.sender || '?'}: ${prompt}`;
    }).join('\n');
}

/**
 * @param {string} projectName
 * @returns {string} markdown context block (or '' if no signal at all)
 */
function buildContext(projectName) {
    // SecretCo is Bedrock-only: its notes never go into a context, whoever asks.
    if (restrictedGuard.mentionsRestricted(String(projectName || ''))) return '';
    if (!projectName) return '';
    const proj = projects.getProjectByName(projectName) || { name: projectName, path: null, description: '' };

    const sections = [];
    sections.push(`# CONTEXT_PRELUDE (auto-generated by TSRCT dispatcher)`);
    sections.push(`Project: **${proj.name}**`);
    if (proj.path) sections.push(`Path: \`${proj.path}\``);
    if (proj.description) sections.push(`Summary: ${proj.description}`);
    sections.push('');

    const vault = vaultPageFor(proj.name);
    if (vault) {
        sections.push(`## Vault page (\`vault/projects/${proj.name}.md\`)`);
        sections.push(vault.trim());
        sections.push('');
    }

    const git = gitLogFor(proj.path);
    if (git) {
        sections.push('## Recent commits');
        sections.push('```');
        sections.push(git);
        sections.push('```');
        sections.push('');
    }

    const recent = recentTaskSummary(proj.name);
    if (recent) {
        sections.push('## Recent dispatched tasks for this project');
        sections.push(recent);
        sections.push('');
    }

    const decisions = decisionsLogSnippet(proj.name);
    if (decisions) {
        sections.push('## Relevant decisions log entries');
        sections.push(decisions);
        sections.push('');
    }

    sections.push('---');
    sections.push('# YOUR TASK');

    const out = sections.join('\n');
    return clip(out, MAX_TOTAL_CHARS);
}

module.exports = { buildContext };
